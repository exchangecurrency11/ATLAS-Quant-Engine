      "4H context FILTER on qualifying BOS, never an independent trade.",
      "",
      "**Strict:** V9 same 6 fixed chronological expanding folds and same official "
      "Binance history, 4H target prediction T−5m, then BOS at time >=T. "
      "All variants rerun V7 full sequentially. NO past-trade winner filtering. "
      "Historical periods were already inspected, and must NOT be reused "
      "for parameter selection or claimed as truly unseen.",
