PAIRS=("BTCUSDT","SOLUSDT")
REF={"BTCUSDT":"BTCUSDT_PERP.A","SOLUSDT":"SOLUSDT_PERP.A"}
AS_OF=ts("2026-10-01T00:00:00Z")
PERIOD_START=ts("2024-10-01T00:00:00Z")
MODE="V9_V7_PLUS_BOS_RETEST_FULL_CHRONOLOGICAL_PROFIT_BACKTEST_HISTORICAL"
VARIANTS=("V7_ORIGINAL","V9_94_DIRECTION_GATE",
          "V9_88_NO_TX_DIRECTION_GATE","V9_94_AND_88_AGREEMENT_GATE",
          "V9_QUALITY_SCORE_60","V9_QUALITY_SCORE_75")
BPS_BASE=9
BPS_STRESS=25


def original_prediction_map(records):
    mapping={}
    for sym in PAIRS:
        mapping[sym]={}
        for r in records[sym]:
            if r["targetStartUTC"] in mapping[sym]:
                raise ValueError("DUPLICATE_TARGET_V9_FOLD")
            target=ts(r["targetStartUTC"])
            decision=ts(r["decisionUTC"])
            if not target-25*60<=decision<=target-3*60:
                raise ValueError("V9_FOLD_INPUT_WAS_NOT_PREDICTED_PRE_TARGET")
            if target<PERIOD_START or target>=AS_OF:
                continue
            mapping[sym][target]={
                "direction":"bullish" if r["modelPgreen"]>=.5 else "bearish",
                "probGreen":r["modelPgreen"],
                "originalDecisionUTC":decision,
                "target4HStartUTC":target,
                "target4HEndUTC":target+FOUR,
                "fold":r["fold"]}
    return mapping


def gate_at_bos(symbol, predictions94, predictions88, variant, evidence):
    """Compose V7's unchanged BOS-quality filter with a causal, pre-T V9 gate."""
    if variant not in VARIANTS:
        raise ValueError("UNREGISTERED_V9_GATE_VARIANT")
    def signal_quality(bars,bos,indicators):
        original=evaluate_bos_quality(bars,bos,indicators)
        if not original["passed"] or variant=="V7_ORIGINAL":
            return original
        known=int(bars[-1]["t"])+HOUR
        if known%HOUR:
            raise ValueError("BOS_WATCH_NOT_CLOSED_HOUR")
        target=known//FOUR*FOUR
        a=predictions94[symbol].get(target)
        b=predictions88[symbol].get(target)
        evidence["checkedV7QualifyingBOS"]+=1
        if variant=="V9_94_DIRECTION_GATE":
            use=(a,)
        elif variant=="V9_88_NO_TX_DIRECTION_GATE":
            use=(b,)
        else:
            use=(a,b)
        if any(x is None for x in use):
            evidence["rejectedNoV9PrestartForecast"]+=1
            return {**original,"passed":False,
                    "reasons":list(original["reasons"])+["V9_4H_CONTEXT_UNAVAILABLE_NO_TRADE"]}
        for x in use:
            if not (x["originalDecisionUTC"]<x["target4HStartUTC"]<=known
                <x["target4HEndUTC"] or x["originalDecisionUTC"]<known==x["target4HStartUTC"]):
                raise ValueError("V9_HISTORICAL_DIRECTION_GATE_FUTURE_LEAK")
            if x["direction"]!=bos["direction"]:
                evidence["rejectedDirectionalDisagreement"]+=1
                return {**original,"passed":False,
                        "reasons":list(original["reasons"])+["V9_PRESEALED_4H_COLOR_AGAINST_BOS"]}
        evidence["V9DirectionAlignedV7BOS"]+=1
        return original
    return signal_quality


def cost_adjust(t,one_way_bps):
    """The original paper report already subtracts 9bp per side."""
    return float(t["netRIllustrative"])-(
        2*(one_way_bps-BPS_BASE)/10000*
        float(t["entry"])/float(t["risk"]))


def metrics(report,lo=PERIOD_START,hi=AS_OF):
    if report["status"]!="PAPER_BACKTEST_NOT_LIVE":
        raise ValueError("V7_PAPER_BASELINE_NOT_VERIFIED")
    trades=[t for t in report["trades"] if lo<=t["entryOpenUTC"]<hi and
            t["exitKnownUTC"]<=hi]
    r=[cost_adjust(t,BPS_BASE) for t in trades]
    stress=[cost_adjust(t,BPS_STRESS) for t in trades]
    n=len(trades)
    gain=sum(max(x,0) for x in r)
    loss=-sum(min(x,0) for x in r)
    dd=0;peak=0;eq=0
    for t in sorted(trades,key=lambda t:(t["exitKnownUTC"],t["entryOpenUTC"])):
        eq+=cost_adjust(t,BPS_BASE)
        peak=max(peak,eq)
        dd=max(dd,peak-eq)
    return {
      "V7paperClosedTrades":n,
      "originalV7BOSWatchCountCumulativeSimulator":report["alertsCount"],
      "winningTrades9BpsPerSide":sum(x>0 for x in r),
      "winRatePct9BpsPerSide":round(100*sum(x>0 for x in r)/n,2) if n else None,
      "totalNetR9BpsPerSide":round(sum(r),4) if n else None,
      "averageNetR9BpsPerSide":round(sum(r)/n,4) if n else None,
      "totalNetR25BpsPerSideStress":round(sum(stress),4) if n else None,
      "averageNetR25BpsPerSideStress":round(sum(stress)/n,4) if n else None,
      "profitFactorR":round(gain/loss,3) if loss else None,
      "maxPeakToTroughRDrawdown":round(dd,4) if n else None,
      "originalV7BOSQualityRejected":report["qualityGateRejectedBOS"],
      "v7RetestRejected":report["qualityGateRejectedRetest"],
      "v7NoRetestCount":report["retestExpiredCount"],
      "v7RiskRejected":report["riskRuleRejected"],
      "stillUnresolvedExcluded":report["unresolvedPositionExcluded"],
      "tradeRetestWasObservedBeforeEntry":all(
         t["watchKnownUTC"]<=t["retestKnownUTC"]<=t["entryOpenUTC"]
         for t in trades),
      "fundingVariableSpreadTrueFillAndLiquidationNOTIncluded":True,
    }


def run(v7inputs,v9data=None,v9obs=None,source=None):
    # Source collection is part of pipeline; a known historical ZIP list
    # with no cherry-picked 2026-Oct/Nov additions.
    if v9data is None:
        v9data,source=download_three()
    p=prepare(v9data)
    obs,excluded=observations(p) if v9obs is None else (v9obs,{})
    _,rec94=fit_and_predict(obs)
    _,rec88=fit_and_predict(transform_observations(obs))
    p94=original_prediction_map(rec94)
    p88=original_prediction_map(rec88)
    for sym in PAIRS:
        if set(p94[sym])!=set(p88[sym]):
            raise ValueError("V9_94_88_NOT_SAME_4H_TIMELINE")
    prices={s:{b["t"]:b for b in v9data[s]["one"]} for s in PAIRS}
    for s in PAIRS:
        history=v7inputs["1hour"][REF[s]]
        if any(history[i]["t"]+HOUR!=history[i+1]["t"] for i in range(len(history)-1)):
            raise ValueError("ORIGINAL_V7_HOURLY_MISSING_BARS_"+s)
        # Independently reconcile official Binance 1H OHLC: no replay
        # if source definitions differ during the V9 test window.
        checked=0
        for h in history:
            if h["t"]<PERIOD_START or h["t"]>=AS_OF:continue
            matched=prices[s].get(h["t"])
            if matched is None:
                raise ValueError("V9_PRICE_SOURCE_MISSING_V7_HOUR_"+s)
            for k in ("o","h","l","c"):
                if abs(h[k]-matched[k])>max(1e-6,abs(h[k])*2e-5):
                    raise ValueError("V9_BINANCE_V7_PRICE_FIELD_PARITY_MISMATCH_"+s)
            checked+=1
        if checked<10000:
            raise ValueError("NOT_ENOUGH_COMMON_VERIFIED_HISTORY_"+s)
    pairs={}
    full={}
    for s in PAIRS:
        h=v7inputs["1hour"][REF[s]]
        four=v7inputs["4hour"][REF[s]]
        day=v7inputs["daily"][REF[s]]
        pairs[s]={}
        for variant in VARIANTS:
            events={"checkedV7QualifyingBOS":0,
                    "rejectedNoV9PrestartForecast":0,
                    "rejectedDirectionalDisagreement":0,
                    "V9DirectionAlignedV7BOS":0}
            if variant in SCORE_CANDIDATES:
                threshold=SCORE_CANDIDATES[variant]
                def quality_gate(bars,bos,indicators, threshold=threshold):
                    original=evaluate_bos_quality(bars,bos,indicators)
                    return gate_v7_with_quality(
                        bars,bos,indicators,original,threshold,events)
                gate=quality_gate
            else:
                gate=gate_at_bos(s,p94,p88,variant,events)
            out=replay_pair(h,four,day,as_of=AS_OF,bos_quality_filter=gate)
            stat=metrics(out)
            stat["V9BOSDirectionFilterAudit"]=events
            stat["filtersOnlyV7AlreadyQualifyingBOS"]=True
            stat["fullySequentialSameOriginalV7Candles"]=True
            stat["next1HOpenPaperEntryAndSameStopTPTimingAsV7"]=True
            pairs[s][variant]=stat
            full.setdefault(s,{})[variant]=out
    summary={}
    for s in PAIRS:
        a=pairs[s]["V7_ORIGINAL"]
        summary[s]={}
        for variant in VARIANTS[1:]:
            c=pairs[s][variant]
            summary[s][variant]={
              "baseTrades":a["V7paperClosedTrades"],
              "candidateTrades":c["V7paperClosedTrades"],
              "candidateMinusBaselineMeanNetR":round(
                  c["averageNetR9BpsPerSide"]-a["averageNetR9BpsPerSide"],4)
                  if c["averageNetR9BpsPerSide"] is not None and
                     a["averageNetR9BpsPerSide"] is not None else None,
              "candidateMinusBaselineTotalNetR":round(
                  c["totalNetR9BpsPerSide"]-a["totalNetR9BpsPerSide"],4)
                  if c["totalNetR9BpsPerSide"] is not None and
                     a["totalNetR9BpsPerSide"] is not None else None,
              "improvesNetRAndProfitFactorWithEnoughTrades":False,
              "neverPromoteFromThesePreviouslyExploredHistoricalBars":True}
    result={
      "status":MODE,"sourceWindowStartUTC":iso(PERIOD_START),
      "asOfExclusiveUTC":iso(AS_OF),
      "V7StrategyIsPrimary":True,
      "V9PredictedOwn4HCandleColorIsOnlyOptionalPreknownBOSGate":True,
      "V994UsesHistoricalSixFoldExpandingModelsNotSepFrozenInPast":True,
      "V988ShadowUsesExactSameSixFoldsNoPostSelection":True,
      "V9ForecastTMinus5MinutesForEach4HBeforeBOSSignal":True,
      "newV9QualityV7OnlyRegimeFVGOBLiquidityResearch":True,
      "qualityThresholdsPredeclaredBeforeNewResultExecution":SCORE_CANDIDATES,
      "qualityOnlyUsesClosed1HAtOriginalV7BOS":True,
      "qualityScoresNotCalibratedProfitProbabilities":True,
      "dojiExcluded":excluded,
      "prospectiveOrPreviouslyUnseenOutOfSample":False,
      "historicalDataAlreadyInspectedAndNoFilterSelectionPermitted":True,
      "V7ArchiveEndsAfterTestButSameTargetSubsetOnly":True,
      "allSourcePricesStrictlyReconciledWithOriginalV7":True,
      "sameChronologicalSimulationAndRiskStopTPForEachVariant":True,
      "baselineCostBpsPerSide":BPS_BASE,
      "stressCostBpsPerSide":BPS_STRESS,
      "candidateHistorical":pairs,
      "candidateMinusV7":summary,
      "netRIsIllustrativeNotRealUSDReturn":True,
      "notAProvenProfitableAutomatedSystem":True,
      "noBrokerOrders":True,"noUserNotifications":True,
      "productionV7AndOriginalV9ModelsNotModified":True,
      "modelOrAlertPromotionBlocked":True}
    # This is what the user wants: reconstruct ACTUAL historical paper
    # entries from the independently replayed V7 BOS/retest 1H bars,
    # with stop/TP/fees and realistic illustrative 100 USDT capital/margin.
    # All candidate variants were replayed chronologically. No omitted
    # losing trades or future candle data is used at entry.
    result["historicalPaperTradeLedger"]=journal_report(
        reconstruct(full,v7inputs))
    return result


