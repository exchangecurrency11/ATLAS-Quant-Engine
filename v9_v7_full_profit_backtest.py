def main():
    p=argparse.ArgumentParser()
    p.add_argument("--v7-archive",default="v7_archived")
    p.add_argument("--output",default="forward/v9_v7_profit_backtest/compare.json")
    p.add_argument("--markdown",default="forward/v9_v7_profit_backtest/compare.md")
    a=p.parse_args()
    folder=Path(a.v7_archive)
    data={}
    for tf in ("1hour","4hour","daily"):
        path=folder/f"history_{tf}.json"
        if not path.is_file():raise ValueError("VERIFIED_V7_SOURCE_HISTORY_ARTIFACT_NOT_PRESENT")
        payload=json.loads(path.read_text())
        if set(x["symbol"] for x in payload)!=set(REF.values()):
            raise ValueError("V7_SOURCE_NOT_EXACTLY_BTC_AND_SOL")
        data[tf]={x["symbol"]:x["history"] for x in payload}
    result=run(data)
    paper=result.pop("historicalPaperTradeLedger")
    result["generatedUTC"]=iso(int(datetime.now(timezone.utc).timestamp()))
    result["individualHistoricalPaperTradesWrittenAndValidated"]=len(
        paper["allCompletedHistoricalPaperTradeLedger"])
    result["paperTradeLedgerFolder"]="forward/v9_v7_profit_backtest/paper_trades"
    save_artifacts(paper,"forward/v9_v7_profit_backtest/paper_trades")
    for filename,body in ((a.output,json.dumps(result,ensure_ascii=False,indent=2)+"\n"),
                          (a.markdown,report_md(result))):
        out=Path(filename)
        out.parent.mkdir(parents=True,exist_ok=True)
        out.write_text(body)
    print("V9_V7_PROFIT_PRIMARY_FULL_SEQUENTIAL_HISTORICAL_REPLAY_COMPLETE",
          json.dumps({s:{v:{"trades":m["V7paperClosedTrades"],
                           "avgNetR":m["averageNetR9BpsPerSide"],
                           "totalNetR":m["totalNetR9BpsPerSide"]}
                         for v,m in x.items()}
                     for s,x in result["candidateHistorical"].items()}),
          flush=True)


if __name__=="__main__":
    main()
