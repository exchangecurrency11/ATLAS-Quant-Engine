def iso(ts):
    return datetime.fromtimestamp(ts,timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

def validate_rows(bars,secs,as_of):
    if not bars or any(
        not math.isfinite(bar[k]) for bar in bars for k in ("t","o","h","l","c","v")
    ):
        raise ValueError("INVALID_OHLCV_NUMBERS")
    if any(bars[i]["t"]+secs!=bars[i+1]["t"] for i in range(len(bars)-1)):
        raise ValueError("DISCONTINUOUS_HISTORY")
    if bars[-1]["t"]+secs>as_of:
        raise ValueError("FUTURE_CANDLE_INCLUDED")
    return True

def coinalyze_history(key,tf):
    seconds=SECS[tf]
    days={"1hour":15,"4hour":145,"daily":300}[tf]
    query=urlencode({"symbols":PAIR,"interval":tf,
                     "from":TARGET-days*86400,"to":TARGET+90})
    req=Request(SOURCE+"?"+query,method="GET",
                headers={"api_key":key,"User-Agent":"SOL-V81-roleflip-paper-research/1.0",
                         "Accept":"application/json"})
    with urlopen(req,timeout=40) as res:
        if res.status!=200:raise RuntimeError("COINALYZE_NON_200")
        raw=res.read(2500000)
    data=json.loads(raw)
    if not isinstance(data,list) or len(data)!=1 or data[0].get("symbol")!=PAIR:
        raise ValueError("WRONG_PERPETUAL_SYMBOL")
    bars=candles_from_history(data[0].get("history",[]),tf,as_of=TARGET)
    validate_rows(bars,seconds,TARGET)
    if len(bars)<{"1hour":300,"4hour":750,"daily":250}[tf]:
        raise ValueError("INSUFFICIENT_HISTORICAL_CLOSED_CANDLES_"+tf)
    expected=TARGET//seconds*seconds
    if bars[-1]["t"]+seconds!=expected:
        raise ValueError("LIVE_LAST_BAR_STALE_"+tf)
    return bars,sha256(raw).hexdigest()

def joined_1h_4h(history):
    h=history["1hour"]
    bar4=history["4hour"][-1]
    end=bar4["t"]+14400
    match=[b for b in h if end-14400<=b["t"]<end]
    if len(match)!=4:raise ValueError("NONMATCHING_RECENT_1H_AND_4H")
    aggregate_data={"o":match[0]["o"],"h":max(b["h"] for b in match),
                    "l":min(b["l"] for b in match),"c":match[-1]["c"],
                    "v":sum(b["v"] for b in match)}
    for k,val in aggregate_data.items():
        if abs(val-bar4[k])>max(1e-5,abs(val)*2e-6):
            raise ValueError("FUTURES_1H_4H_DISAGREE_"+k)
    return True

def zone_overlap(bar,lo,hi):
    return bar["h"]>=lo and bar["l"]<=hi

def user_zone_audit(history):
    bars=history["4hour"]
    day=history["daily"]
    lo,hi=USER_ZONE
    latest=bars[-1]
    last120=bars[-min(len(bars),720):]
    # Every event/retest occurred by the timestamp of the closed 4H candle.
    cross=[]
    for i in range(1,len(last120)):
        prev,cur=last120[i-1],last120[i]
        if prev["c"]>=lo and cur["c"]<lo:
            cross.append({"closeUTC":iso(cur["t"]+14400),
                          "close":round(cur["c"],4),
                          "open":round(cur["o"],4)})
    lastbreak=cross[-1] if cross else None
    retests=[]
    if lastbreak:
        break_ts=int(datetime.fromisoformat(lastbreak["closeUTC"].replace("Z","+00:00")).timestamp())
        for bar in last120:
            when=bar["t"]+14400
            if when<=break_ts:continue
            if zone_overlap(bar,lo,hi):
                retests.append({"closeUTC":iso(when),"high":round(bar["h"],4),
                                "low":round(bar["l"],4),"close":round(bar["c"],4),
                                "closedBackBelow":bar["c"]<lo,
                                "closedIntoZone":lo<=bar["c"]<=hi,
                                "closedAboveZone":bar["c"]>hi})
    hist_touch=[b for b in last120 if zone_overlap(b,lo,hi)]
    close_inside=[b for b in last120 if lo<=b["c"]<=hi]
    rsi=indicators(day)
    ema20=ema([b["c"] for b in day],20)
    dClose=day[-1]["c"]
    return {
      "manualZone":{"low":lo,"high":hi,"width":round(hi-lo,4),
                    "pctOfLatestClose":round((hi-lo)/latest["c"]*100,3)},
      "statusAtTarget":"BELOW_USER_ZONE_SUPPORT_BROKEN_CANDIDATE" if latest["c"]<lo
          else "ABOVE_USER_ZONE" if latest["c"]>hi else "INSIDE_USER_ZONE",
      "latest4H":{"closeUTC":iso(latest["t"]+14400),
                  "open":latest["o"],"high":latest["h"],
                  "low":latest["l"],"close":latest["c"],"volume":latest["v"]},
      "confirmedDaily":{"closeUTC":iso(day[-1]["t"]+86400),
                        "close":dClose,"RSI14":round(rsi["RSI14"],3),
                        "EMA20":round(ema20,4)},
      "all4HBarsOverlappingZoneLast120Days":len(hist_touch),
      "fourHourClosesInsideZoneLast120Days":len(close_inside),
      "lastBrokenSupportCrossing4H":lastbreak,
      "retestCandlesSinceLastBreak":retests[-10:],
      "retestCountSinceLastBreak":len(retests),
      "confirmedRejectionAfterLastBreak":any(x["closedBackBelow"] for x in retests),
      "institutionalOrderBlockProven":False,
      "ictBreakerSweepProven":False,
      "important":"User's band is an ex-post annotation; not an algorithm-found or live-traded edge.",
    }

def official_history(start,end,workers=6):
    months=months_inclusive(start,end)
    start_ts=month_start(start)
    finish=month_end(end)
    if not 3<=len(months)<=24 or finish>int(datetime.now(timezone.utc).timestamp()):
        raise ValueError("INVALID_ARCHIVE_MONTHS")
    monthly={}
    proofs=[]
    with ThreadPoolExecutor(max_workers=workers) as pool:
        jobs={pool.submit(download_month,COIN,m):m for m in months}
        for f in as_completed(jobs):
            s,m,bars,proof=f.result()
            if s!=COIN or m!=jobs[f]:raise ValueError("WRONG_BINANCE_ARCHIVE")
            monthly[m]=bars
            proofs.append({"month":m,"sha256":proof["sha256"],
                           "source":proof["url"],"bars":len(bars)})
            print("BINANCE_SHA256_VERIFIED",m,len(bars),flush=True)
    one=[b for m in months for b in monthly[m]]
    expected=(finish-start_ts)//3600
    if len(one)!=expected or any(b["t"]!=start_ts+3600*i for i,b in enumerate(one)):
        raise ValueError("MISSING_MONTHLY_1H")
    four=aggregate(one,14400)
    daily=aggregate(one,86400)
    validate_rows(four,14400,finish)
    validate_rows(daily,86400,finish)
    return four,daily,proofs

def atr(bars,i):
    return average_true_range(bars,i,14)

def candidates(bars):
    """Support pivot + confirmed post-pivot displacement; all evidence CLOSED.

    Span 3 swing becomes knowable after 3 closes; an impulse over the NEXT
    6 bars is knowable only at pivot+6, not at pivot candle.
    Zone includes wick/body of the pivot with 0.25 ATR14 fixed padding.
    This is a measurable structural-demand heuristic, NOT an ICT order block.
    """
    output=[]
    span=3
    for i in range(30,len(bars)-7):
        w=bars[i-span:i+span+1]
        candle=bars[i]
        if not (candle["l"]==min(x["l"] for x in w)
                and sum(x["l"]==candle["l"] for x in w)==1):
            continue
        known=i+6
        volatility=atr(bars,i+span)
        if not volatility or volatility<=0:continue
        low=candle["l"]-.25*volatility
        high=max(candle["o"],candle["c"])+.25*volatility
        if high<=low or (high-low)/candle["c"]>.07:
            continue
        if max(b["c"] for b in bars[i+1:i+7])<high+.70*volatility:
            continue
        output.append({"originIndex":i,"knownIndex":known,
                       "knownUTC":iso(bars[known]["t"]+14400),
                       "originUTC":iso(candle["t"]+14400),
                       "zoneLow":round(low,7),"zoneHigh":round(high,7),
                       "zoneWidthPct":round(100*(high-low)/candle["c"],3),
                       "confirmedPriorRiseATR":.70})
    return output

def detect_break_and_retest(bars,zone):
    lo,hi=zone["zoneLow"],zone["zoneHigh"]
    confirmed=zone["knownIndex"]
    # A meaningful separation from prior support is required to remove
    # choppy level crossings; only data BEFORE breakdown is used.
    first=confirmed+12
    for b in range(first,len(bars)-1):
        vol=atr(bars,b)
        if not vol:continue
        last_closes=[x["c"] for x in bars[max(confirmed,b-30):b]]
        if not last_closes or max(last_closes)<hi+vol:
            continue
        if (bars[b-1]["c"]>=lo and bars[b]["c"]<lo-.20*vol):
            # First support breakdown; no retroactive reclassification if
            # later realized price movement looks favourable.
            for r in range(b+1,min(b+49,len(bars)-1)):
                x=bars[r]
                if x["c"]>hi:
                    return {"state":"RECLAIMED_NO_BEARISH_RETEST",
                            "breakIndex":b,"reclaimIndex":r}
                if x["h"]>=lo and x["l"]<=hi:
                    if x["c"]<lo and x["c"]<x["o"]:
                        return {"state":"BEARISH_RETEST_REJECTED",
                                "breakIndex":b,"retestIndex":r,"entryIndex":r+1}
                    # first touch not a rejection; keep waiting
            return {"state":"NO_QUALIFIED_RETEST_WITHIN_48_4H",
                    "breakIndex":b}
    return {"state":"NO_QUALIFIED_BREAK"}

def paper_outcome(bars,zone,signal,horizon=18):
    idx=signal["entryIndex"]
    if idx>=len(bars):return None
    price=bars[idx]["o"]
    rejection=bars[signal["retestIndex"]]
    vol=atr(bars,signal["retestIndex"])
    stop=max(zone["zoneHigh"],rejection["h"])+.15*vol
    distance=stop-price
    if price<=0 or distance<=0 or not .001<=distance/price<=.04:
        return {"status":"RISK_UNSUITABLE_NO_TRADE"}
    target=price-2*distance
    max_end=min(idx+horizon,len(bars))
    reason="TIME_EXIT"
    exit_price=bars[max_end-1]["c"]
    exit_at=max_end
    for j in range(idx,max_end):
        bar=bars[j]
        if bar["h"]>=stop:
            reason="STOP_FIRST"
            exit_price=stop
            exit_at=j+1
            break
        if bar["l"]<=target:
            reason="TARGET_2R"
            exit_price=target
            exit_at=j+1
            break
    if max_end<len(bars) and reason=="TIME_EXIT":
        # Time exit is the close of the final candle.
        pass
    if max_end==len(bars) and reason=="TIME_EXIT":
        return {"status":"UNRESOLVED_AT_ARCHIVE_END"}
    cost=2*FEE_AND_SLIPPAGE_BPS_PER_SIDE/10000*price
    netR=(price-exit_price-cost)/distance
    qty=min(PAPER_RISK_USDT/(distance+cost),
            PAPER_EQUITY*PAPER_LEVERAGE/price)
    if qty<0:raise ValueError("INVALID_QTY")
    usd=qty*(price-exit_price-cost)
    return {"status":"COMPLETED_HYPOTHETICAL",
            "entryIndex":idx,"exitIndexExclusive":exit_at,
            "entryUTC":iso(bars[idx]["t"]),
            "exitKnownUTC":iso(bars[exit_at-1]["t"]+14400),
            "entry":round(price,5),"stop":round(stop,5),
            "target2R":round(target,5),
            "zoneLow":zone["zoneLow"],"zoneHigh":zone["zoneHigh"],
            "netR":round(netR,6),"netPnLUSDT":round(usd,6),
            "riskCapUSDT":PAPER_RISK_USDT,
            "marginUsedUSDT":round(qty*price/PAPER_LEVERAGE,5),
            "exitReason":reason}

def summarize(trades,lo,hi):
    items=[t for t in trades if lo<=t["entryIndexTimestamp"]<hi]
    vals=[t["netR"] for t in items]
    gains=sum(max(0,x) for x in vals)
    losses=sum(-min(0,x) for x in vals)
    return {"trades":len(items),
            "winCount":sum(v>0 for v in vals),
            "winPct":round(100*sum(v>0 for v in vals)/len(vals),2) if vals else None,
            "meanNetR":round(mean(vals),4) if vals else None,
            "totalNetR":round(sum(vals),4),
            "profitFactorR":round(gains/losses,4) if losses else None,
            "hypotheticalUSDPerIndependent0_5Risk":round(sum(x["netPnLUSDT"] for x in items),5),
            "details":[{k:v for k,v in x.items() if k!="entryIndexTimestamp"} for x in items]}

def historical_roleflip(bars):
    zones=candidates(bars)
    events=[]
    retests=[]
    for z in zones:
        signal=detect_break_and_retest(bars,z)
        events.append({**{k:v for k,v in z.items() if k not in ("knownIndex","originIndex")},**{
            "status":signal["state"],
            "breakKnownUTC":iso(bars[signal["breakIndex"]]["t"]+14400)
                if "breakIndex" in signal else None,
            "retestKnownUTC":iso(bars[signal["retestIndex"]]["t"]+14400)
                if "retestIndex" in signal else None}})
        if signal["state"]=="BEARISH_RETEST_REJECTED":
            result=paper_outcome(bars,z,signal)
            if result and result["status"]=="COMPLETED_HYPOTHETICAL":
                retests.append(result)
    # Prevent overlapping concurrent fills in a single-account replay.
    retests.sort(key=lambda x:(x["entryIndex"],x["zoneLow"]))
    selected=[]
    previous_exit=-1
    for t in retests:
        if t["entryIndex"]<previous_exit:continue
        selected.append(t)
        previous_exit=t["exitIndexExclusive"]
    for x in selected:
        x["entryIndexTimestamp"]=bars[x["entryIndex"]]["t"]
    min_ts=bars[0]["t"]
    end_ts=bars[-1]["t"]+14400
    stats={
      "candidates":len(zones),
      "eventStatuses":dict(Counter(x["status"] for x in events)),
      "rawOverlappingCompletedPaperTrades":len(retests),
      "nonOverlappingCompletedPaperTrades":len(selected),
      "beforeSplit":summarize(selected,min_ts,SPLIT),
      "reusedEarlierHoldout":summarize(selected,SPLIT,end_ts),
      "methodNotICTBreakerStrict":True,
      "notOutOfSample":True,
      "noPortfolioEquityClaim":True,
    }
    return stats,events

